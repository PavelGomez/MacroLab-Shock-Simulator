/* Integración de la ventana: DOM/audio simulados; no certifica un navegador. */
'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert/strict'),crypto=require('crypto');
const {JSDOM,VirtualConsole}=require('jsdom');
let checks=0;const ok=(v,m)=>{assert.ok(v,m);checks++};
const errors=[],vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM(fs.readFileSync(path.join(__dirname,'index.html'),'utf8'),{url:'https://example.test/MacroLab-Shock-Simulator/macro1/index.html?clase=8#route',runScripts:'dangerously',pretendToBeVisual:true,virtualConsole:vc,beforeParse(w){
 w.HTMLCanvasElement.prototype.getContext=()=>new Proxy({},{get:(t,k)=>k==='measureText'?()=>({width:10}):()=>{},set:()=>true});
 w.Element.prototype.scrollIntoView=()=>{};
 w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
 w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'))};
}});
const w=dom.window,d=w.document;
w.eval(fs.readFileSync(path.join(__dirname,'presentacion-clase8.js'),'utf8'));
const dialog=d.getElementById('class8-narration'),frame=dialog.querySelector('iframe');
const entry=()=>d.querySelector('[data-presentation="class8"]');
ok(w.MacroLabLoop.activeClass()==='8','enlace de curso selecciona Clase 8');
ok(d.querySelectorAll('[data-presentation="class8"]').length===1,'acceso único desde la teoría de Clase 8');
ok(entry().href.endsWith('/macro1/presentaciones/mundell-fleming/index.html'),'enlace directo relativo correcto');
ok(!frame.hasAttribute('src'),'no carga la presentación antes de solicitarla');
d.getElementById('c8-read').click();
const before=JSON.stringify(w.MacroLabLoop.classState()['8']);
entry().click();
ok(dialog.open&&d.body.classList.contains('narration-open'),'abre ventana de estudio');
ok(d.activeElement===dialog.querySelector('[data-narration-close]'),'foco inicial en cerrar');
ok(frame.src.endsWith('/macro1/presentaciones/mundell-fleming/index.html'),'iframe usa el paquete alojado');
let pauses=0;frame.contentWindow.MFPlayer={pause(){pauses++}};
const src=frame.getAttribute('src');
dialog.querySelector('[data-narration-close]').click();
ok(!dialog.open&&pauses>0,'cerrar detiene la voz antes de ocultar');
ok(!d.body.classList.contains('narration-open')&&d.activeElement===entry(),'devuelve foco y desplazamiento de la ruta');
ok(JSON.stringify(w.MacroLabLoop.classState()['8'])===before,'conserva íntegro el avance de Clase 8');
entry().click();
ok(frame.getAttribute('src')===src&&frame.contentWindow.MFPlayer,'reabrir conserva el reproductor y su punto');
w.dispatchEvent(new w.MessageEvent('message',{source:frame.contentWindow,origin:'https://otro.test',data:{type:'macrolab-narration:close'}}));
ok(dialog.open,'ignora mensajes de otro origen');
w.dispatchEvent(new w.MessageEvent('message',{source:frame.contentWindow,origin:w.location.origin,data:{type:'macrolab-narration:close'}}));
ok(!dialog.open,'Volver a Clase 8 desde la presentación cierra la ventana');
entry().click();dialog.dispatchEvent(new w.Event('cancel',{cancelable:true}));
ok(!dialog.open&&d.activeElement===entry(),'Escape conserva el retorno en pausa');
d.getElementById('class-tab-2').click();ok(!entry(),'el acceso no invade otras clases');
ok(errors.length===0,'carga y navegación sin errores: '+errors.join('; '));
const base=path.join(__dirname,'presentaciones/mundell-fleming'),timeline=JSON.parse(fs.readFileSync(path.join(base,'production/timeline.json')));
ok(timeline.slides.length===24&&timeline.chapters.length===7,'paquete completo de 24 diapositivas y siete capítulos');
ok(timeline.visualRevision==='4-interceptos-opcionales','publica la revisión aprobada con interceptos opcionales');
const manifest=JSON.parse(fs.readFileSync(path.join(base,'verification/revision-v4.json')));
for(const [file,hash]of Object.entries(manifest.audio_sha256))ok(crypto.createHash('sha256').update(fs.readFileSync(path.join(base,'assets/audio',file))).digest('hex')===hash,'audio aprobado intacto: '+file);
ok(fs.existsSync(path.join(base,'COMPARTIR_Mundell_Fleming_Macro1.zip')),'ZIP autónomo disponible para descargar');
dom.window.close();console.log(`${checks} comprobaciones de integración narrada aprobadas (DOM simulado).`);
